export const useThemeStore = defineStore('theme', {
  state: () => ({
    currentTheme: localStorage.getItem('fileshare-theme') || 'light'
  }),

  getters: {
    theme: (state) => themes[state.currentTheme] || themes.light,
    themeList: () => Object.entries(themes).map(([key, val]) => ({ key, ...val })),
    isDark: (state) => (themes[state.currentTheme] || themes.light).mode === 'dark'
  },

  actions: {
    setTheme(themeKey) {
      if (!themes[themeKey]) return
      this.currentTheme = themeKey
      localStorage.setItem('fileshare-theme', themeKey)
      this.applyTheme()
    },

    applyTheme() {
      const theme = this.theme
      const root = document.documentElement

      for (const [key, value] of Object.entries(theme.vars)) {
        root.style.setProperty(key, value)
      }

      root.dataset.theme = this.currentTheme

      if (theme.mode === 'light') {
        document.body.classList.add('theme-light')
        document.body.classList.remove('theme-dark')
        document.documentElement.classList.remove('dark')
      } else {
        document.body.classList.add('theme-dark')
        document.body.classList.remove('theme-light')
        document.documentElement.classList.add('dark')
      }
    }
  }
})
